export function getTheme(name = "space") {
  const key = String(name ?? "space").toLowerCase();
  if (!THEMES[key]) {
    throw new Error(`Unknown theme "${name}". Available themes: ${Object.keys(THEMES).join(", ")}`);
  }
  return THEMES[key];
}

